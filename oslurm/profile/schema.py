def category_for(event_type: str | TraceEventType) -> TraceCategory:
    value = event_type.value if isinstance(event_type, TraceEventType) else str(event_type)
    for prefix, category in EVENT_CATEGORIES.items():
        if value.startswith(prefix):
            return category
    return TraceCategory.SIMULATION


@dataclass(frozen=True)
class TraceHeader:
    run_id: RunId
    sequence: int
    wall_time_ns: int
    simulation_time_ns: int
    event_type: str
    node_id: str | None
    job_id: str | None
    correlation_id: CorrelationId | None
    parent_event_id: EventId | None
    event_id: EventId


@dataclass(frozen=True)
class TraceEvent:
    schema_version: int
    header: TraceHeader
    category: str
    source: str
    payload: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "header": asdict(self.header),
            "category": self.category,
            "source": self.source,
            "payload": self.payload,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "TraceEvent":
        header = TraceHeader(**data["header"])
        return cls(
            schema_version=int(data.get("schema_version", 0)),
            header=header,
            category=str(data.get("category", category_for(header.event_type).value)),
            source=str(data.get("source", "unknown")),
            payload=dict(data.get("payload", {})),
        )
